GLYPH_W, GLYPH_H = 5, 7
_cache = {}


def _glyph_surface(ch, color, scale):
    key = (ch, color, scale)
    surf = _cache.get(key)
    if surf is not None:
        return surf
    rows = GLYPHS.get(ch, GLYPHS['?'])
    surf = pygame.Surface((GLYPH_W * scale, GLYPH_H * scale), pygame.SRCALPHA)
    for y, row in enumerate(rows):
        for x, cell in enumerate(row):
            if cell == '#':
                surf.fill(color, (x * scale, y * scale, scale, scale))
    _cache[key] = surf
    return surf


def text_width(text, scale=1, spacing=1):
    if not text:
        return 0
    return len(text) * (GLYPH_W + spacing) * scale - spacing * scale


def draw_text(target, text, x, y, color=(255, 255, 255), scale=1, spacing=1,
              shadow=None, center=False, right=False):
    """Blit `text` (auto-uppercased) and return the x position after it."""
    text = text.upper()
    if center:
        x -= text_width(text, scale, spacing) // 2
    elif right:
        x -= text_width(text, scale, spacing)
    if shadow is not None:
        for dx, dy in ((scale, scale),):
            cx = x + dx
            for ch in text:
                target.blit(_glyph_surface(ch, shadow, scale), (cx, y + dy))
                cx += (GLYPH_W + spacing) * scale
    cx = x
    for ch in text:
        target.blit(_glyph_surface(ch, color, scale), (cx, y))
        cx += (GLYPH_W + spacing) * scale
    return cx
